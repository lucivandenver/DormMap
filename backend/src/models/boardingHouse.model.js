export const BoardingHouseModel = (sequelize, DataTypes) => sequelize.define('boarding_house', {
  name: { type: DataTypes.STRING, allowNull: false },
  owner_id: { type: DataTypes.INTEGER, allowNull: false },
  barangay_id: { type: DataTypes.INTEGER, allowNull: false },
  address: { type: DataTypes.TEXT, allowNull: true },
  latitude: { type: DataTypes.STRING, allowNull: false },
  longitude: { type: DataTypes.STRING, allowNull: false },
  permit_number: { type: DataTypes.STRING, allowNull: true },
  permit_expiration: { type: DataTypes.DATE, allowNull: true },
  total_rooms: { type: DataTypes.INTEGER, defaultValue: 0 },
  available_rooms: { type: DataTypes.INTEGER, defaultValue: 0 },
  occupied_rooms: { type: DataTypes.INTEGER, defaultValue: 0 },
  contact_number: { type: DataTypes.STRING, allowNull: true },
  description: { type: DataTypes.TEXT, allowNull: true },
  is_active: { type: DataTypes.BOOLEAN, defaultValue: true },
  is_verified: { type: DataTypes.BOOLEAN, defaultValue: false },
  gallery_images: { type: DataTypes.JSON, allowNull: true },
  amenities: { type: DataTypes.JSON, allowNull: true },
  house_rules: { type: DataTypes.JSON, allowNull: true },
});
